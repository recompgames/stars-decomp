/* Differential-test driver (docs/PLAN.md section 4, task stars-dwf.3). Native only.
 *
 * From one snapshot of the arena, runs an original function in Unicorn and its
 * decompiled C twin, then compares return registers, arena bytes (excluding the
 * callee's scratch stack) and the ordered API call log.
 *
 * Segment argument "seg": a value below 0x100 is an NE segment number (selector
 * seg << 3), anything else is used as a selector (scratch code from
 * harness_alloc_code in self-tests). Argument words are given as for
 * harness_call (see harness/harness.h). DIFF runs need harness_load first.
 */
#ifndef STARS_HARNESS_DIFFTEST_H
#define STARS_HARNESS_DIFFTEST_H

#include <stdint.h>
#include <string.h>

#include "harness/harness.h"
#include "runtime/frame.h"

/* Adapter: reads the arguments from the emulated stack (ss:sp points at the
 * return address) and calls the C function. For REGISTER functions regs is the
 * register file (in and out). Returns DX:AX. */
typedef uint32_t (*DtAdapter)(uint16_t ss, uint16_t sp, Regs16 *regs);

typedef struct DtEntry {
  uint16_t seg, off;
  const char *name;
  int conv;      /* DtConv */
  DtAdapter adapter;
  int ret_words; /* 0 void/registers, 1 AX, 2 DX:AX */
} DtEntry;

/* Generated by tools/gen_registry.py into build/registry.c. */
extern const DtEntry dt_registry[];
extern const unsigned dt_registry_count;

/* Argument access for adapters: the value at byte offset off from ss:sp. */
static inline uint32_t dt_stack_read(uint16_t ss, uint16_t sp, unsigned off, unsigned bytes) {
  uint32_t v = 0;
  memcpy(&v, LIN(MK_FP(ss, (uint16_t)(sp + off))), bytes);
  return v;
}
#define DT_ARG16(ss, sp, off) ((uint16_t)dt_stack_read((ss), (sp), (off), 2))
#define DT_ARG32(ss, sp, off) dt_stack_read((ss), (sp), (off), 4)

/* Runtime registration (self-tests, hand-written adapters). Entries registered
 * here win over the generated table. The entry is copied; name must be static. */
void difftest_register(const DtEntry *e);
void difftest_unregister_all(void);
const DtEntry *difftest_lookup(uint16_t seg, uint16_t off);

/* Function extent for coverage, normally taken from docs/functions.csv. */
void difftest_set_extent(uint16_t seg, uint16_t off, uint32_t size, const char *name);

typedef enum { DT_PASS, DT_FAIL, DT_MISSING } DtStatus;

typedef struct DtResult {
  DtStatus status;
  char msg[512];   /* first difference, or empty */
  uint32_t ret;    /* DX:AX of the ORIGINAL run */
  Regs16 regs;     /* registers after the ORIGINAL run (REGISTER functions) */
} DtResult;

/* Non-fatal single DIFF; does not touch the summary. in may be NULL (REGISTER
 * functions start from those registers). */
DtResult difftest_run(uint16_t seg, uint16_t off, int conv, const uint16_t *args, int nargs,
                      const Regs16 *in);
/* nargs random 16-bit arguments per iteration (xorshift32, seed). Stops at the
 * first failing iteration; its message names the arguments. */
DtResult difftest_fuzz_run(uint16_t seg, uint16_t off, int conv, int nargs, unsigned iterations,
                           uint32_t seed);

/* Recording variants used by the macros: print failures to stderr, add to the
 * summary, return the status. */
DtStatus difftest_diff(uint16_t seg, uint16_t off, int conv, const uint16_t *args, int nargs);
DtStatus difftest_fuzz(uint16_t seg, uint16_t off, int conv, int nargs, unsigned iterations,
                       uint32_t seed);

/* Prints the per-function summary (PASS/FAIL/MISSING and coverage %). Returns 1
 * if any function failed or is missing, else 0: end a scenario with
 * "return difftest_summary();". */
int difftest_summary(void);

/* Forgets every recorded status (not the coverage): lets one test binary record
 * a FAIL or MISSING on purpose and still end with a clean summary. */
void difftest_reset_summary(void);
/* Worst status recorded for the function by the recording variants (PASS < FAIL
 * < MISSING), or -1 when nothing was recorded. */
int difftest_recorded_status(uint16_t seg, uint16_t off);

/* Coverage of the ORIGINAL function so far, in percent (-1 when unknown). */
double difftest_coverage(uint16_t seg, uint16_t off);

#define DIFF(seg, off, conv, ...)                                           \
  ({                                                                        \
    const uint16_t dt_a_[] = {0, __VA_ARGS__};                              \
    difftest_diff((seg), (off), (conv), dt_a_ + 1, (int)(sizeof dt_a_ / 2) - 1); \
  })
#define DIFF_FUZZ(seg, off, conv, nargs, iterations, seed) \
  difftest_fuzz((seg), (off), (conv), (nargs), (iterations), (seed))

/* rt_call_far: ORIGINAL always emulates; DECOMP uses the registry's C function
 * when one exists, else emulates. fn is a far pointer (selector:offset); the
 * selector below 0x100 means an NE segment number as in DIFF. */
enum { RT_MODE_ORIGINAL, RT_MODE_DECOMP };
void rt_set_mode(int mode);
/* uint32_t rt_call_far(uint32_t fn, int conv, const uint16_t *args, int nargs); is declared in
 * runtime/frame.h (it has a wasm counterpart there). */

#endif /* STARS_HARNESS_DIFFTEST_H */
