"""Tests for tools/gen_imports.py, run against the vendored Wine spec files.

Expected values were checked by hand against tools/winespec/*.spec at
wine-mirror/wine commit 5b6b85421c2a2161728b2a55e9f09271770a3eb0.
"""
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
sys.path.insert(0, str(TOOLS))

import gen_imports as g  # noqa: E402

SPEC_DIR = TOOLS / "winespec"


class VendoredSpecs(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.records = g.parse_spec_dir(SPEC_DIR)
        cls.funcs = {(r.module, r.ordinal): r for r in cls.records if isinstance(r, g.Func)}
        cls.equs = {(r.module, r.ordinal): r for r in cls.records if isinstance(r, g.Equ)}

    def assertFunc(self, module, ordinal, name, kind, argbytes, ret):
        f = self.funcs.get((module, ordinal))
        self.assertIsNotNone(f, f"no function record for {module} {ordinal}")
        self.assertEqual(f.name, name)
        self.assertEqual(f.kind, kind)
        self.assertEqual(f.argbytes, argbytes)
        self.assertEqual(f.ret, ret)

    def test_user_1_messagebox_pascal_12_ret16(self):
        self.assertFunc("USER", 1, "MessageBox", "PASCAL", 12, "RET16")

    def test_user_171_winhelp_pascal_12_ret16(self):
        # word(2) str(4) word(2) long(4)
        self.assertFunc("USER", 171, "WinHelp", "PASCAL", 12, "RET16")

    def test_user_420_wsprintf_varargs_counts_fixed_args_only(self):
        # _wsprintf(ptr str): fixed args 4 + 4 = 8
        self.assertFunc("USER", 420, "_wsprintf", "VARARGS", 8, "RET16")

    def test_gdi_34_bitblt_pascal_20_ret16(self):
        # word s_word s_word s_word s_word word s_word s_word long = 2*8 + 4
        self.assertFunc("GDI", 34, "BitBlt", "PASCAL", 20, "RET16")

    def test_kernel_82_lread_pascal_8_ret16(self):
        self.assertFunc("KERNEL", 82, "_lread", "PASCAL", 8, "RET16")

    def test_kernel_3_getversion_no_ret16_means_ret32(self):
        self.assertFunc("KERNEL", 3, "GetVersion", "PASCAL", 0, "RET32")

    def test_register_entries_are_register_with_no_return(self):
        self.assertFunc("KERNEL", 91, "InitTask", "REGISTER", 0, "NONE")
        self.assertFunc("KERNEL", 102, "DOS3Call", "REGISTER", 0, "NONE")
        self.assertFunc("WIN87EM", 1, "__fpMath", "REGISTER", 0, "NONE")

    def test_commdlg_20_printdlg_pascal_4_ret16(self):
        self.assertFunc("COMMDLG", 20, "PrintDlg", "PASCAL", 4, "RET16")

    def test_toolhelp_80_timercount_pascal_4_ret16(self):
        self.assertFunc("TOOLHELP", 80, "TimerCount", "PASCAL", 4, "RET16")

    def test_equates_have_expected_values(self):
        self.assertEqual(self.equs[("KERNEL", 113)].name, "__AHSHIFT")
        self.assertEqual(self.equs[("KERNEL", 113)].value, 3)
        self.assertEqual(self.equs[("KERNEL", 114)].name, "__AHINCR")
        self.assertEqual(self.equs[("KERNEL", 114)].value, 8)
        self.assertEqual(self.equs[("KERNEL", 178)].name, "__WINFLAGS")
        self.assertEqual(self.equs[("KERNEL", 178)].value, 0x413)

    def test_win32_at_lines_are_skipped(self):
        # krnl386.exe16.spec lines 552+ are "@ stdcall -arch=win32" entries, not Win16 imports.
        names = {r.name for r in self.records if isinstance(r, g.Func) and r.module == "KERNEL"}
        self.assertNotIn("k32CharToOemA", names)
        self.assertNotIn("Win32HandleToDosFileHandle", names)

    def test_render_has_generated_comment_and_macro_lines(self):
        text = g.render(self.records)
        self.assertTrue(text.startswith("/* This file is generated by tools/gen_imports.py"))
        self.assertIn('W16API(USER, 1, "MessageBox", PASCAL, 12, RET16)\n', text)
        self.assertIn('W16EQU(KERNEL, 178, "__WINFLAGS", 1043)\n', text)  # 1043 == 0x413


def _fixture_dir(d, user_spec_text):
    """Copy the five unchanged vendored spec files into d and write user.exe16.spec as given."""
    for src in SPEC_DIR.glob("*.spec"):
        if src.name != "user.exe16.spec":
            Path(d, src.name).write_bytes(src.read_bytes())
    Path(d, "user.exe16.spec").write_text(user_spec_text, encoding="utf-8")


class CommittedInclude(unittest.TestCase):
    def test_committed_win16_api_inc_matches_generator_output(self):
        # A stale or hand-edited runtime/win16_api.inc must fail here (make test).
        committed = (TOOLS.parent / "runtime" / "win16_api.inc").read_bytes()
        expected = g.render(g.parse_spec_dir(SPEC_DIR)).encode("utf-8")
        self.assertEqual(committed, expected,
                         "runtime/win16_api.inc is stale: run make runtime/win16_api.inc")


class ParserErrors(unittest.TestCase):
    def test_unknown_argument_type_raises_naming_the_type(self):
        with tempfile.TemporaryDirectory() as d:
            _fixture_dir(d, "1 pascal Foo(quux) Foo16\n")
            with self.assertRaises(g.SpecError) as ctx:
                g.parse_spec_dir(Path(d))
            self.assertIn("quux", str(ctx.exception))

    def test_duplicate_ordinal_in_one_spec_file_raises_naming_the_ordinal(self):
        with tempfile.TemporaryDirectory() as d:
            _fixture_dir(d, "1 pascal Foo() Foo16\n1 pascal Bar() Bar16\n")
            with self.assertRaises(g.SpecError) as ctx:
                g.parse_spec_dir(Path(d))
            self.assertIn("1", str(ctx.exception))
            self.assertIn("duplicate", str(ctx.exception))

    def test_cli_exits_nonzero_and_names_unknown_type(self):
        with tempfile.TemporaryDirectory() as d:
            _fixture_dir(d, "1 pascal Foo(quux) Foo16\n")
            proc = subprocess.run(
                [sys.executable, "-I", str(TOOLS / "gen_imports.py"), d],
                capture_output=True, text=True,
            )
            self.assertNotEqual(proc.returncode, 0)
            self.assertIn("quux", proc.stderr)


if __name__ == "__main__":
    unittest.main()
