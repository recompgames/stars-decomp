#!/usr/bin/env python3
"""Generate the Win16 import table from the vendored Wine 16-bit spec files.

Usage: python3 tools/gen_imports.py tools/winespec > runtime/win16_api.inc

Reads the six spec files in tools/winespec/ (see SOURCE.md there) and prints
one macro line per entry:
  W16API(MODULE, ordinal, "name", KIND, argbytes, RET)   for functions and stubs
  W16EQU(MODULE, ordinal, "name", value)                 for equates
Stdlib only. Exits 1 with a message on stderr if the input cannot be parsed.
"""
import re
import sys
from collections import namedtuple
from pathlib import Path

# Spec file name -> module name used in the output.
MODULES = {
    "krnl386.exe16.spec": "KERNEL",
    "user.exe16.spec": "USER",
    "gdi.exe16.spec": "GDI",
    "commdlg.dll16.spec": "COMMDLG",
    "toolhelp.dll16.spec": "TOOLHELP",
    "win87em.dll16.spec": "WIN87EM",
}

# Argument type -> size in bytes on the Win16 stack.
ARG_SIZES = {
    "word": 2,
    "s_word": 2,
    "long": 4,
    "ptr": 4,
    "str": 4,
    "segptr": 4,
    "segstr": 4,
}

Func = namedtuple("Func", "module ordinal name kind argbytes ret")
Equ = namedtuple("Equ", "module ordinal name value")

# Kinds whose calls do not use the stack return convention (no RET16/RET32).
NO_RET_KINDS = ("REGISTER", "STUB", "VARIABLE")


class SpecError(Exception):
    pass


def _parse_line(module, path, lineno, line):
    """Return a Func, an Equ, or None (blank, comment, or Win32 '@' line)."""
    s = line.split("#", 1)[0].strip()
    if not s or not s[0].isdigit():
        return None  # blank/comment, or '@ stdcall -arch=win32' (not Win16)

    where = f"{path}:{lineno}"
    tokens = s.split()
    if len(tokens) < 2:
        raise SpecError(f"{where}: malformed entry {line.strip()!r}")
    ordinal, src_kind = int(tokens[0]), tokens[1]

    if src_kind == "equate":
        if len(tokens) != 4:
            raise SpecError(f"{where}: equate needs a name and a value: {line.strip()!r}")
        return Equ(module, ordinal, tokens[2], int(tokens[3], 0))

    if src_kind not in ("pascal", "varargs", "stub", "variable"):
        raise SpecError(f"{where}: unknown entry kind {src_kind!r}")

    if "(" in s:
        open_at = s.index("(")
        close_at = s.find(")", open_at)
        if close_at < 0:
            raise SpecError(f"{where}: unclosed '(' in {line.strip()!r}")
        head_tokens = s[:open_at].split()
        args = s[open_at + 1:close_at].split()
    else:
        if src_kind in ("pascal", "varargs"):
            raise SpecError(f"{where}: {src_kind} entry without an argument list: {line.strip()!r}")
        head_tokens = tokens
        args = []

    name = head_tokens[-1]
    flags = [t for t in head_tokens[2:-1] if t.startswith("-")]

    if src_kind == "pascal":
        kind = "REGISTER" if "-register" in flags else "PASCAL"
    elif src_kind == "varargs":
        kind = "VARARGS"
    elif src_kind == "stub":
        kind = "STUB"
    else:
        kind = "VARIABLE"

    argbytes = 0
    if kind not in ("STUB", "VARIABLE"):  # variable data words in '(0 0 ...)' are not types
        for arg in args:
            if arg not in ARG_SIZES:
                raise SpecError(f"{where}: unknown argument type {arg!r} in {name}")
            argbytes += ARG_SIZES[arg]

    if kind in NO_RET_KINDS:
        ret = "NONE"
    elif "-ret16" in flags:
        ret = "RET16"
    else:
        ret = "RET32"

    return Func(module, ordinal, name, kind, argbytes, ret)


def parse_spec_file(module, path):
    records = []
    first_line = {}  # ordinal -> line number where it first appeared
    with open(path, encoding="utf-8") as fh:
        for lineno, line in enumerate(fh, 1):
            rec = _parse_line(module, path, lineno, line)
            if rec is not None:
                if rec.ordinal in first_line:
                    raise SpecError(
                        f"{path}:{lineno}: duplicate ordinal {rec.ordinal} in {module} "
                        f"(first at line {first_line[rec.ordinal]})"
                    )
                first_line[rec.ordinal] = lineno
                records.append(rec)
    return records


def parse_spec_dir(spec_dir):
    """Parse every module in MODULES, in MODULES order. Strict about file names."""
    spec_dir = Path(spec_dir)
    present = {p.name for p in spec_dir.glob("*.spec")}
    unknown = present - set(MODULES)
    if unknown:
        raise SpecError(f"no module mapping for spec file(s): {', '.join(sorted(unknown))}")
    records = []
    for fname, module in MODULES.items():
        path = spec_dir / fname
        if not path.is_file():
            raise SpecError(f"missing spec file: {path}")
        records.extend(parse_spec_file(module, path))
    return records


HEADER = (
    "/* This file is generated by tools/gen_imports.py from tools/winespec/ (see SOURCE.md).\n"
    " * Do not edit. The includer defines the macros first:\n"
    " *   W16API(module, ordinal, name, kind, argbytes, ret)\n"
    " *   W16EQU(module, ordinal, name, value)\n"
    " * argbytes and RET are meaningless for STUB and VARIABLE entries (encoded as 0 / NONE);\n"
    " * REGISTER entries still pop their declared argbytes; VARARGS argbytes is the fixed-argument\n"
    " * total, the caller pops.\n"
    " */\n"
)


def render(records):
    out = [HEADER]
    for r in records:
        if isinstance(r, Func):
            out.append(
                f'W16API({r.module}, {r.ordinal}, "{r.name}", {r.kind}, {r.argbytes}, {r.ret})\n'
            )
        else:
            out.append(f'W16EQU({r.module}, {r.ordinal}, "{r.name}", {r.value})\n')
    return "".join(out)


def main(argv):
    if len(argv) != 2:
        print("usage: gen_imports.py SPEC_DIR > win16_api.inc", file=sys.stderr)
        return 2
    try:
        records = parse_spec_dir(argv[1])
    except SpecError as exc:
        print(f"gen_imports: {exc}", file=sys.stderr)
        return 1
    sys.stdout.write(render(records))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
