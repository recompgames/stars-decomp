#!/usr/bin/env python3
"""Tests for tools/gen_globals.py (fixture: tools/fixtures/globals.csv)."""
import sys
import tempfile
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import gen_globals as g  # noqa: E402

FIX = HERE / "fixtures" / "globals.csv"


class GenGlobalsTest(unittest.TestCase):
    def gen(self, text):
        return g.generate(text)

    def test_int16_label_gives_exact_macro_line(self):
        out = self.gen("name,offset,type\ncounter,0x1234,int16_t\n")
        self.assertIn("#define g_counter (*(int16_t *)LINN(0x1234))\n", out)

    def test_fixture_file(self):
        out = self.gen(FIX.read_text())
        self.assertIn("#define g_flags (*(uint8_t *)LINN(0x0010))\n", out)
        self.assertIn("#define g_total (*(uint32_t *)LINN(0x2000))\n", out)
        self.assertIn("#define g_table ((uint16_t *)LINN(0x3000))\n", out)
        self.assertIn("#define g_oddword (*(uint16_ua *)LINN(0x0011))\n", out)
        # sorted by offset: flags (0x10) before counter (0x1234)
        self.assertLess(out.index("g_flags"), out.index("g_counter"))

    def test_misaligned_offset_uses_align1_typedef(self):
        # odd offset for a 16-bit global, offset not a multiple of 4 for a 32-bit one, and an
        # array of 16-bit elements at an odd offset: a plain (uint16_t *) cast is UB there.
        out = self.gen("name,offset,type\nodd,0x0011,uint16_t\nmid,0x0022,int32_t\n"
                       "arr,0x0031,int16_t[4]\nok,0x0040,uint16_t\nb,0x0051,uint8_t\n")
        self.assertIn("#define g_odd (*(uint16_ua *)LINN(0x0011))\n", out)
        self.assertIn("#define g_mid (*(int32_ua *)LINN(0x0022))\n", out)
        self.assertIn("#define g_arr ((int16_ua *)LINN(0x0031))\n", out)
        self.assertIn("#define g_ok (*(uint16_t *)LINN(0x0040))\n", out)    # aligned stays plain
        self.assertIn("#define g_b (*(uint8_t *)LINN(0x0051))\n", out)      # bytes never need it
        self.assertIn("typedef uint16_t uint16_ua __attribute__((aligned(1)));", out)
        self.assertIn("typedef int32_t int32_ua __attribute__((aligned(1)));", out)

    def test_header_guard_and_generated_banner(self):
        out = self.gen("name,offset,type\n")
        self.assertIn("Generated by tools/gen_globals.py", out)
        self.assertIn("#ifndef STARS_SRC_GLOBALS_H", out)
        self.assertIn('#include "runtime/mem.h"', out)
        self.assertTrue(out.rstrip().endswith("#endif"))

    def test_ghidra_names_are_sanitised(self):
        out = self.gen("name,offset,type\nDAT_1110_4b9c,0x4b9c,uint16_t\n")
        self.assertIn("#define g_DAT_1110_4b9c (*(uint16_t *)LINN(0x4b9c))", out)
        out = self.gen("name,offset,type\nbad name.x,0x0004,uint8_t\n")
        self.assertIn("#define g_bad_name_x ", out)

    def test_comment_column_is_emitted_above_the_macro(self):
        out = self.gen('name,offset,type,comment\n'
                       'selected_planet,0x4b84,uint16_t,"seg05.c: planet index, -1 when none"\n'
                       'plain,0x0010,uint8_t,\n'
                       'tricky,0x0020,uint8_t,"ends */ early"\n')
        self.assertIn("/* seg05.c: planet index, -1 when none */\n"
                      "#define g_selected_planet (*(uint16_t *)LINN(0x4b84))\n", out)
        self.assertIn("\n#define g_plain (*(uint8_t *)LINN(0x0010))\n", out)    # no comment, no line
        self.assertNotIn("/* */", out)
        self.assertIn("/* ends *\\/ early */\n#define g_tricky ", out)        # cannot close the comment

    def test_errors(self):
        for bad, pat in (("a,0x10000,int16_t\n", "offset"),
                         ("a,0x10,int\n", "type"),
                         ("a,0x10,char\n", "type"),
                         ("a,zz,int16_t\n", "offset"),
                         ("a,0x10,int16_t\na,0x20,int16_t\n", "duplicate"),
                         ("a,0x10,uint16_t[0]\n", "type")):
            with self.subTest(bad=bad):
                with self.assertRaisesRegex(g.GenError, pat):
                    self.gen("name,offset,type\n" + bad)

    def test_overlap_is_an_error(self):
        with self.assertRaisesRegex(g.GenError, "overlap"):
            self.gen("name,offset,type\na,0x10,uint32_t\nb,0x12,uint16_t\n")
        with self.assertRaisesRegex(g.GenError, "past"):
            self.gen("name,offset,type\na,0xfffe,uint32_t\n")

    def test_main_writes_file_and_exit_codes(self):
        with tempfile.TemporaryDirectory() as d:
            out = Path(d) / "sub" / "globals.h"
            self.assertEqual(g.main(["--csv", str(FIX), "-o", str(out)]), 0)
            self.assertIn("LINN(0x1234)", out.read_text())
            self.assertEqual(g.main(["--csv", str(Path(d) / "missing.csv"), "-o", str(out)]), 1)


if __name__ == "__main__":
    unittest.main()
