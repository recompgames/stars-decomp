#!/usr/bin/env python3
"""Generate src/globals.h: accessor macros for the game's DGROUP globals.

usage: gen_globals.py [--csv FILE] [-o OUT]       defaults: re/globals.csv  src/globals.h

Input is the CSV written by ghidra/ExportGlobals.java: name,offset,type[,comment]
  name    a Ghidra data label (characters outside [A-Za-z0-9_] become '_')
  offset  hex offset inside DGROUP (segment 35, selector 0x0118), 0x0000-0xFFFF
  type    int8_t uint8_t int16_t uint16_t int32_t uint32_t, optionally with an element
          count, e.g. uint16_t[8] (then the macro is a pointer to the first element)
  comment optional one-line evidence for the name (the Ghidra end-of-line comment); written as a
          /* ... */ line above the macro, with any "*/" inside it defanged
Each row becomes
  #define g_<name> (*(<type> *)LINN(0x<offset>))        scalar
  #define g_<name> ((<type> *)LINN(0x<offset>))         array
A 16/32-bit global whose offset is not a multiple of its size uses the align-1 typedef
(uint16_ua, int16_ua, uint32_ua, int32_ua, emitted in the header) so the access is not UB.
LINN() (runtime/mem.h) is the transient host pointer into DGROUP: never store it.
Errors (exit 1): bad offset or type, duplicate name, ranges that overlap or run past 0xFFFF.
"""
import csv
import io
import re
import sys
from pathlib import Path

SIZES = {"int8_t": 1, "uint8_t": 1, "int16_t": 2, "uint16_t": 2, "int32_t": 4, "uint32_t": 4}
UA = {b: b[:-2] + "_ua" for b in ("int16_t", "uint16_t", "int32_t", "uint32_t")}   # align-1 typedefs
TYPE_RE = re.compile(r"^(\w+)(?:\[(\d+)\])?$")


class GenError(Exception):
    pass


def parse_type(t, where):
    m = TYPE_RE.match(t.strip())
    if not m or m.group(1) not in SIZES or (m.group(2) is not None and int(m.group(2)) == 0):
        raise GenError(f"{where}: unsupported type '{t}' (use int8_t, uint8_t, int16_t, uint16_t, "
                       "int32_t or uint32_t, optionally with [N], N > 0)")
    return m.group(1), (int(m.group(2)) if m.group(2) else None)


def generate(text):
    rows = []
    rd = csv.reader(io.StringIO(text))
    next(rd, None)
    for n, row in enumerate(rd, start=2):
        if not row or not any(c.strip() for c in row):
            continue
        where = f"line {n}"
        if len(row) < 3:
            raise GenError(f"{where}: expected name,offset,type")
        name, off_s, typ = row[0].strip(), row[1].strip(), row[2].strip()
        try:
            off = int(off_s, 0)
        except ValueError:
            raise GenError(f"{where}: bad offset '{off_s}'") from None
        if not 0 <= off <= 0xFFFF:
            raise GenError(f"{where}: offset {off_s} is outside DGROUP (0x0000-0xFFFF)")
        base, count = parse_type(typ, where)
        size = SIZES[base] * (count or 1)
        if off + size > 0x10000:
            raise GenError(f"{where}: '{name}' extends past 0xFFFF (offset {off_s}, {size} bytes)")
        ident = "g_" + re.sub(r"[^A-Za-z0-9_]", "_", name)
        comment = " ".join(row[3].split()).replace("*/", "*\\/") if len(row) > 3 else ""
        rows.append((off, size, ident, base, count, where, comment))
    seen = {}
    for r in rows:
        if r[2] in seen:
            raise GenError(f"{r[5]}: duplicate name '{r[2]}', first at {seen[r[2]]}")
        seen[r[2]] = r[5]
    rows.sort(key=lambda r: (r[0], r[2]))
    for a, b in zip(rows, rows[1:]):
        if a[0] + a[1] > b[0]:
            raise GenError(f"{b[5]}: '{b[2]}' at 0x{b[0]:04x} overlaps '{a[2]}' "
                           f"(0x{a[0]:04x}, {a[1]} bytes)")
    out = ["/* Generated by tools/gen_globals.py from Ghidra's DGROUP labels. Do not edit. */",
           "#ifndef STARS_SRC_GLOBALS_H", "#define STARS_SRC_GLOBALS_H", "",
           "#include <stdint.h>", '#include "runtime/mem.h"', ""]
    for base in ("int16_t", "uint16_t", "int32_t", "uint32_t"):
        out.append(f"typedef {base} {UA[base]} __attribute__((aligned(1)));")
    out.append("")
    for off, _size, ident, base, count, _w, comment in rows:
        # a cast to a naturally aligned type is undefined behaviour at a misaligned offset (the
        # original code stores words at odd offsets), so those use the align-1 typedef
        t = UA[base] if SIZES[base] > 1 and off % SIZES[base] else base
        if comment:
            out.append(f"/* {comment} */")
        if count is None:
            out.append(f"#define {ident} (*({t} *)LINN(0x{off:04x}))")
        else:
            out.append(f"#define {ident} (({t} *)LINN(0x{off:04x}))")
    out += ["", "#endif", ""]
    return "\n".join(out)


def main(argv):
    csv_path, out = "re/globals.csv", "src/globals.h"
    args = list(argv)
    try:
        while args:
            a = args.pop(0)
            if a == "--csv":
                csv_path = args.pop(0)
            elif a == "-o":
                out = args.pop(0)
            else:
                print(__doc__, file=sys.stderr)
                return 2
        text = generate(Path(csv_path).read_text(encoding="utf-8"))
    except (GenError, OSError, IndexError) as e:
        print(f"gen_globals: error: {e}", file=sys.stderr)
        return 1
    outp = Path(out)
    outp.parent.mkdir(parents=True, exist_ok=True)
    tmp = outp.with_name(outp.name + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(outp)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
